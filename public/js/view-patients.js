(function () {
  'use strict';
  const { html, icon, $, $$ } = GP;

  const GROUPS = ['A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'];
  const ORGANS = ['None', 'Kidney', 'Liver', 'Heart', 'Cornea', 'Bone Marrow'];
  const PAGE = 20;

  // ------------------------------------------------------------------ shared pieces
  function eligChip(p) {
    const e = p.eligibility;
    if (!e) return '';
    if (e.eligible) return html`<span class="chip good">${icon('badge-check')} Eligible donor</span>`;
    return html`<span class="chip" title="${e.reasons.join('. ')}">Not eligible</span>`;
  }
  function statusChips(p) {
    return html`<span class="chips">
      ${p.needsBlood ? html`<span class="chip bad">${icon('droplet')} Needs blood</span>` : ''}
      ${p.needsOrgan !== 'None' ? html`<span class="chip warn">${icon('heart-pulse')} Needs ${p.needsOrgan}</span>` : ''}
      ${p.flags.length ? html`<span class="chip warn" title="${p.flags.join(', ')}">${icon('triangle-alert')} ${GP.plural(p.flags.length, 'flag')}</span>` : ''}
      ${!p.needsBlood ? eligChip(p) : ''}
      ${p.dataSource === 'simulated' ? html`<span class="chip violet">Simulated</span>` : ''}
      ${p.dataSource === 'imported' ? html`<span class="chip info">Imported</span>` : ''}
      ${!p.consent ? html`<span class="chip bad" title="Excluded from donor matching until consent is recorded">No consent</span>` : ''}
    </span>`;
  }

  // ------------------------------------------------------------------ patient card (QR, details, print)
  GP.openCard = async function openCard(id) {
    let p;
    try {
      p = ((await GP.api('GET', `/api/patients/${encodeURIComponent(id)}`)).patient);
    } catch (e) { GP.errorToast(e); return; }

    let qr = '';
    try {
      const q = window.qrcode(0, 'M');
      q.addData(`${location.origin}/#/patient/${p.id}`);
      q.make();
      qr = q.createSvgTag(4, 0);
    } catch { qr = ''; }

    const lab = (v, unit) => (v === null || v === undefined ? html`<span class="faint">not recorded</span>` : `${v} ${unit}`);
    const body = html`
      <div class="pcard-top">
        <div class="pcard-qr" role="img" aria-label="QR code that opens this record">${GP.raw(qr)}</div>
        <dl class="kv">
          <dt>Name</dt><dd><strong>${p.name}</strong></dd>
          <dt>ID</dt><dd class="mono">${p.id}</dd>
          <dt>Blood group</dt><dd>${GP.bgBadge(p.bloodGroup)}</dd>
          <dt>Age / sex</dt><dd>${p.age ?? '-'} / ${p.sex}</dd>
          <dt>Phone</dt><dd>${GP.phoneActions(p.phone, 'Hello, this is regarding blood donation.')}</dd>
          <dt>Last donated</dt><dd>${GP.fmtDay(p.lastDonated)}</dd>
        </dl>
      </div>
      <hr>
      <dl class="kv">
        <dt>Hemoglobin</dt><dd>${lab(p.hb, 'g/dL')}</dd>
        <dt>WBC</dt><dd>${lab(p.wbc, '/µL')}</dd>
        <dt>Glucose</dt><dd>${lab(p.glucose, 'mg/dL')}</dd>
        <dt>Flags</dt><dd>${p.flags.length ? html`<span class="chips">${p.flags.map((f) => html`<span class="chip warn">${f}</span>`)}</span>` : html`<span class="chip good">None</span>`}</dd>
        <dt>Donor status</dt><dd>${p.needsBlood ? html`<span class="chip bad">Currently a blood recipient</span>`
          : p.eligibility.eligible ? html`<span class="chip good">${icon('badge-check')} Eligible donor</span>`
            : html`<ul class="err-list">${p.eligibility.reasons.map((r) => html`<li>${r}</li>`)}</ul>`}</dd>
        <dt>Needs</dt><dd>${p.needsBlood ? 'Blood' : ''}${p.needsBlood && p.needsOrgan !== 'None' ? ', ' : ''}${p.needsOrgan !== 'None' ? p.needsOrgan : ''}${!p.needsBlood && p.needsOrgan === 'None' ? '-' : ''}</dd>
        <dt>Consent</dt><dd>${p.consent ? html`<span class="chip good">On file</span>` : html`<span class="chip bad">Not recorded</span>`}</dd>
        <dt>Record source</dt><dd>${p.dataSource}</dd>
        <dt>Registered</dt><dd>${GP.fmtDateTime(p.createdAt)}</dd>
      </dl>
      ${p.dataSource === 'simulated' ? html`<p class="sim-note">${icon('triangle-alert')} Values on this record were generated by the demo scanner and are not real measurements.</p>` : ''}`;

    const actions = [{ label: 'Close', value: 'close' }];
    actions.unshift({ label: html`${icon('printer')} Print`, run: () => { document.body.classList.add('printing-card'); window.print(); return false; } });
    if (GP.canWrite()) actions.splice(1, 0, { label: html`${icon('pencil')} Edit`, kind: 'primary', value: 'edit' });
    const result = await GP.dialog({ title: 'Donor card', body, actions, wide: true });
    if (result === 'edit') location.hash = `#/register/${encodeURIComponent(p.id)}`;
  };
  window.addEventListener('afterprint', () => document.body.classList.remove('printing-card', 'printing-report'));

  // ------------------------------------------------------------------ record a donation
  async function donationDialog(p) {
    const done = await GP.dialog({
      title: 'Record donation',
      body: html`<p>Record a donation by <strong>${p.name}</strong> (<span class="mono">${p.id}</span>).</p>
        <div class="field" data-field="date"><label for="don-date">Donation date</label>
          <input id="don-date" type="date" value="${GP.todayISO()}" max="${GP.todayISO()}" min="${p.lastDonated || '1990-01-01'}"></div>
        <p class="hint muted">They become eligible again after the minimum interval (90 days for men, 120 for others).</p>`,
      actions: [{ label: 'Cancel' }, {
        label: 'Save donation', kind: 'primary', value: true,
        run: async (d) => {
          try {
            await GP.api('POST', `/api/patients/${encodeURIComponent(p.id)}/donations`, { date: $('#don-date', d).value });
          } catch (e) {
            if (e.errors) { GP.showErrors(d, e.errors); return false; }
            throw e;
          }
        },
      }],
      onOpen: (d) => $('#don-date', d).focus(),
    });
    if (done) { GP.toast('Donation recorded.', 'ok'); GP.invalidate(); }
    return !!done;
  }

  // ------------------------------------------------------------------ directory
  const dir = { q: '', group: '', status: '', sort: 'newest', page: 1 };

  function applyFilters(list) {
    const q = dir.q.trim().toLowerCase();
    const digits = q.replace(/\D/g, '');
    let out = list.filter((p) => {
      if (q && !(p.name.toLowerCase().includes(q) || p.id.toLowerCase().includes(q) || (digits.length >= 3 && p.phone && p.phone.replace(/\D/g, '').includes(digits)))) return false;
      if (dir.group && p.bloodGroup !== dir.group) return false;
      switch (dir.status) {
        case 'needBlood': return p.needsBlood;
        case 'needOrgan': return p.needsOrgan !== 'None';
        case 'eligible': return p.eligibility.eligible;
        case 'flagged': return p.flags.length > 0;
        case 'noConsent': return !p.consent;
        default: return true;
      }
    });
    const cmp = {
      name: (a, b) => a.name.localeCompare(b.name),
      age: (a, b) => (a.age ?? 999) - (b.age ?? 999),
      group: (a, b) => a.bloodGroup.localeCompare(b.bloodGroup) || a.name.localeCompare(b.name),
    }[dir.sort];
    if (cmp) out = out.slice().sort(cmp);
    return out;
  }

  async function renderDirectory(el) {
    GP.setHtml(el, GP.skeleton(false));
    let all;
    try { all = await GP.loadPatients(true); } catch (e) {
      GP.setHtml(el, GP.errorCard(e)); $('#retry', el).onclick = () => renderDirectory(el); return;
    }
    GP.setHtml(el, html`<div class="view-enter" id="print-area">
      <section class="card" aria-labelledby="h-dir">
        <div class="card-head"><h2 id="h-dir">${icon('users')} Directory</h2><span class="spacer"></span>
          <span class="muted" id="dir-count" role="status"></span>
          <button class="btn btn-ghost btn-sm no-print" id="dir-print">${icon('printer')} Print list</button>
          ${GP.canWrite() ? html`<a class="btn btn-sm no-print" href="#/register">${icon('user-plus')} Register</a>` : ''}</div>
        <div class="toolbar no-print">
          <div class="field search"><label class="sr-only" for="f-q">Search</label>${icon('search')}
            <input id="f-q" type="search" placeholder="Search name, ID or phone" autocomplete="off" value="${dir.q}"></div>
          <div class="field"><label class="sr-only" for="f-group">Blood group</label>
            <select id="f-group"><option value="">All blood groups</option>${GROUPS.concat('Unknown').map((g) => html`<option ${dir.group === g ? 'selected' : ''}>${g}</option>`)}</select></div>
          <div class="field"><label class="sr-only" for="f-status">Status</label>
            <select id="f-status">${[['', 'All records'], ['eligible', 'Eligible donors'], ['needBlood', 'Needs blood'], ['needOrgan', 'Needs organ'], ['flagged', 'Abnormal values'], ['noConsent', 'No consent on file']]
              .map(([v, l]) => html`<option value="${v}" ${dir.status === v ? 'selected' : ''}>${l}</option>`)}</select></div>
          <div class="field"><label class="sr-only" for="f-sort">Sort by</label>
            <select id="f-sort">${[['newest', 'Newest first'], ['name', 'Name A-Z'], ['age', 'Age'], ['group', 'Blood group']]
              .map(([v, l]) => html`<option value="${v}" ${dir.sort === v ? 'selected' : ''}>${l}</option>`)}</select></div>
        </div>
        <div class="table-wrap" tabindex="0" role="region" aria-label="Patient directory table"><table>
          <thead><tr><th>ID</th><th>Name</th><th>Age / sex</th><th>Group</th><th>Status</th><th>Phone</th><th class="no-print"><span class="sr-only">Actions</span></th></tr></thead>
          <tbody id="dir-body"></tbody></table></div>
        <div class="pager no-print" id="dir-pager"></div>
      </section></div>`);

    const draw = () => {
      const rows = applyFilters(all);
      const pages = Math.max(1, Math.ceil(rows.length / PAGE));
      dir.page = Math.min(dir.page, pages);
      const slice = rows.slice((dir.page - 1) * PAGE, dir.page * PAGE);
      const canW = GP.canWrite(); const isAdmin = GP.can('admin');
      GP.setHtml($('#dir-body', el), slice.length ? slice.map((p) => html`<tr>
        <td class="mono nowrap">${p.id}</td>
        <td><strong>${p.name}</strong></td>
        <td class="nowrap">${p.age ?? '-'} / ${p.sex.charAt(0)}</td>
        <td>${GP.bgBadge(p.bloodGroup)}</td>
        <td>${statusChips(p)}</td>
        <td class="nowrap">${p.phone ? (p.phone.startsWith('*') ? p.phone : html`<a href="tel:${p.phone.replace(/[^\d+]/g, '')}">${p.phone}</a>`) : html`<span class="faint">-</span>`}</td>
        <td class="nowrap no-print"><span class="row">
          <button class="btn btn-ghost btn-icon btn-sm" data-act="card" data-id="${p.id}" aria-label="Open card for ${p.name}" title="Card / QR">${icon('qr-code')}</button>
          ${canW ? html`<button class="btn btn-ghost btn-icon btn-sm" data-act="edit" data-id="${p.id}" aria-label="Edit ${p.name}" title="Edit">${icon('pencil')}</button>
            <button class="btn btn-ghost btn-icon btn-sm" data-act="donate" data-id="${p.id}" aria-label="Record donation for ${p.name}" title="Record donation">${icon('calendar-plus')}</button>` : ''}
          ${isAdmin ? html`<button class="btn btn-danger btn-icon btn-sm" data-act="archive" data-id="${p.id}" aria-label="Archive ${p.name}" title="Archive">${icon('archive')}</button>` : ''}
        </span></td></tr>`)
        : html`<tr><td colspan="7">${GP.emptyState('search', all.length ? 'No records match these filters.' : 'No records yet.')}</td></tr>`);
      $('#dir-count', el).textContent = `${rows.length} of ${all.length} records`;
      GP.setHtml($('#dir-pager', el), pages > 1 ? html`
        <span>Page ${dir.page} of ${pages}</span>
        <span class="row"><button class="btn btn-ghost btn-sm" data-page="-1" ${dir.page <= 1 ? 'disabled' : ''}>${icon('chevron-left')} Prev</button>
        <button class="btn btn-ghost btn-sm" data-page="1" ${dir.page >= pages ? 'disabled' : ''}>Next ${icon('chevron-right')}</button></span>` : '');
    };
    draw();

    $('#f-q', el).addEventListener('input', GP.debounce((e) => { dir.q = e.target.value; dir.page = 1; draw(); }, 150));
    $('#f-group', el).addEventListener('change', (e) => { dir.group = e.target.value; dir.page = 1; draw(); });
    $('#f-status', el).addEventListener('change', (e) => { dir.status = e.target.value; dir.page = 1; draw(); });
    $('#f-sort', el).addEventListener('change', (e) => { dir.sort = e.target.value; dir.page = 1; draw(); });
    $('#dir-print', el).addEventListener('click', () => { document.body.classList.add('printing-report'); window.print(); });

    el.onclick = async (e) => {
      const pg = e.target.closest('[data-page]');
      if (pg) { dir.page += Number(pg.dataset.page); draw(); return; }
      const b = e.target.closest('[data-act]');
      if (!b) return;
      const p = all.find((x) => x.id === b.dataset.id);
      if (!p) return;
      if (b.dataset.act === 'card') GP.openCard(p.id);
      if (b.dataset.act === 'edit') location.hash = `#/register/${encodeURIComponent(p.id)}`;
      if (b.dataset.act === 'donate') { if (await donationDialog(p)) renderDirectory(el); }
      if (b.dataset.act === 'archive') {
        const ok = await GP.confirm({ title: 'Archive record', message: `Archive ${p.name} (${p.id})? The record is hidden from the directory and matching. An administrator can restore it from the Archive page.`, confirmLabel: 'Archive', danger: true });
        if (!ok) return;
        try { await GP.api('DELETE', `/api/patients/${encodeURIComponent(p.id)}`); GP.toast('Record archived.', 'ok'); GP.invalidate(); renderDirectory(el); } catch (err) { GP.errorToast(err); }
      }
    };
  }

  // ------------------------------------------------------------------ register / edit form
  function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
  const rnd = (a, b) => Math.floor(Math.random() * (b - a + 1)) + a;

  async function renderRegister(el, id) {
    if (!GP.canWrite()) {
      GP.setHtml(el, html`<div class="card">${GP.emptyState('lock', 'Your account has read-only access, so you cannot register or edit donors.')}</div>`);
      return;
    }
    let p = null;
    if (id) {
      GP.setHtml(el, GP.skeleton(false));
      try { p = (await GP.api('GET', `/api/patients/${encodeURIComponent(id)}`)).patient; } catch (e) {
        GP.setHtml(el, GP.errorCard(e)); $('#retry', el).onclick = () => renderRegister(el, id); return;
      }
    }
    const editing = !!p;
    let mode = editing ? (p.dataSource === 'simulated' ? 'simulated' : 'manual') : 'manual';
    let sim = editing && p.dataSource === 'simulated' && Array.isArray(p.codis)
      ? { bloodGroup: p.bloodGroup, hb: p.hb, wbc: p.wbc, glucose: p.glucose, codis: p.codis } : null;
    const v = (x) => (x === null || x === undefined ? '' : x);

    GP.setHtml(el, html`<div class="view-enter"><form id="pform" class="card" novalidate autocomplete="off" aria-labelledby="h-reg">
      <div class="card-head"><h2 id="h-reg">${icon(editing ? 'pencil' : 'user-plus')} ${editing ? html`Edit record <span class="mono">${p.id}</span>` : 'Register donor / patient'}</h2></div>

      <div class="grid-2">
        <div class="field" data-field="name"><label for="f-name">Full name</label>
          <input id="f-name" name="name" type="text" maxlength="100" required value="${v(p && p.name)}" autocomplete="off"></div>
        <div class="field" data-field="phone"><label for="f-phone">Phone <span class="faint">(optional)</span></label>
          <input id="f-phone" name="phone" type="tel" inputmode="tel" maxlength="20" placeholder="+91 98765 43210" value="${v(p && p.phone)}"></div>
        <div class="field" data-field="age"><label for="f-age">Age</label>
          <input id="f-age" name="age" type="number" inputmode="numeric" min="0" max="120" required value="${v(p && p.age)}"></div>
        <div class="field" data-field="sex"><label for="f-sex">Sex</label>
          <select id="f-sex" name="sex">${['Male', 'Female', 'Other', 'Unknown'].map((s) => html`<option ${p && p.sex === s ? 'selected' : ''}>${s}</option>`)}</select></div>
      </div>

      <div class="field"><span class="label" id="mode-label">Where do the blood values come from?</span>
        <div class="seg" role="radiogroup" aria-labelledby="mode-label">
          <label><input type="radio" name="mode" value="manual" ${mode === 'manual' ? 'checked' : ''}><span>Lab report (enter manually)</span></label>
          <label><input type="radio" name="mode" value="simulated" ${mode === 'simulated' ? 'checked' : ''}><span>Simulated scan (demo)</span></label>
        </div></div>

      <div id="simbox" ${mode === 'simulated' ? '' : 'hidden'}>
        <div class="scanbox" id="scanbox">
          <div id="scan-idle" ${sim ? 'hidden' : ''}><p class="muted">Generates demo values for blood group, hemoglobin, WBC, glucose and an STR marker profile.</p></div>
          <div id="scan-run" hidden><div class="scan-ring">${icon('fingerprint')}</div><strong id="scan-msg">Calibrating&hellip;</strong></div>
          <button type="button" class="btn" id="scan-btn">${icon('scan-line')} ${sim ? 'Re-run scan' : 'Run simulated scan'}</button>
          <p class="sim-note">${icon('triangle-alert')}<span>Simulated values are random demo data, not real measurements. Do not use them for medical decisions.</span></p>
        </div>
      </div>

      <div class="grid-2">
        <div class="field" data-field="bloodGroup"><label for="f-bg">Blood group</label>
          <select id="f-bg" name="bloodGroup" required><option value="">Select&hellip;</option>${GROUPS.map((g) => html`<option ${p && p.bloodGroup === g ? 'selected' : ''}>${g}</option>`)}</select></div>
        <div class="field" data-field="lastDonated"><label for="f-last">Last donation <span class="faint">(optional)</span></label>
          <input id="f-last" name="lastDonated" type="date" max="${GP.todayISO()}" value="${v(p && p.lastDonated)}"></div>
        <div class="field" data-field="hb"><label for="f-hb">Hemoglobin (g/dL)</label>
          <input id="f-hb" name="hb" type="number" inputmode="decimal" step="0.1" min="1" max="30" value="${v(p && p.hb)}"></div>
        <div class="field" data-field="wbc"><label for="f-wbc">WBC (/µL)</label>
          <input id="f-wbc" name="wbc" type="number" inputmode="numeric" min="100" max="100000" value="${v(p && p.wbc)}"></div>
        <div class="field" data-field="glucose"><label for="f-glu">Glucose (mg/dL)</label>
          <input id="f-glu" name="glucose" type="number" inputmode="numeric" min="10" max="1000" value="${v(p && p.glucose)}"></div>
        <div class="field" data-field="needsOrgan"><label for="f-organ">Organ needed</label>
          <select id="f-organ" name="needsOrgan">${ORGANS.map((o) => html`<option ${p && p.needsOrgan === o ? 'selected' : ''}>${o}</option>`)}</select></div>
      </div>

      <div class="field" data-field="needsBlood"><label class="check"><input type="checkbox" name="needsBlood" ${p && p.needsBlood ? 'checked' : ''}><span><strong>Needs a blood transfusion</strong> (adds this person to the blood-matching list)</span></label></div>
      <div class="field" data-field="consent"><label class="check"><input type="checkbox" name="consent" ${p && p.consent ? 'checked' : ''}><span><strong>Consent recorded:</strong> this person agreed to their details being stored and used to contact them about donation. Records without consent are never offered as donors.</span></label></div>

      <div class="row">
        <button class="btn btn-primary" type="submit" id="save-btn">${icon('check')} ${editing ? 'Save changes' : 'Register'}</button>
        ${editing ? html`<a class="btn btn-ghost" href="#/directory">Cancel</a>` : ''}
      </div>
    </form></div>`);

    const form = $('#pform', el);
    const setSimLocked = () => {
      const locked = mode === 'simulated';
      ['f-bg', 'f-hb', 'f-wbc', 'f-glu'].forEach((i) => { const n = $(`#${i}`, form); n.disabled = locked && i === 'f-bg'; n.readOnly = locked && i !== 'f-bg'; });
      $('#simbox', form).hidden = !locked;
    };
    const fillFromSim = () => {
      if (!sim) return;
      $('#f-bg', form).value = sim.bloodGroup; $('#f-hb', form).value = sim.hb;
      $('#f-wbc', form).value = sim.wbc; $('#f-glu', form).value = sim.glucose;
    };
    setSimLocked();

    $$('input[name="mode"]', form).forEach((r) => r.addEventListener('change', () => { mode = r.value; setSimLocked(); if (mode === 'simulated') fillFromSim(); }));

    $('#scan-btn', form).addEventListener('click', async (e) => {
      const btn = e.currentTarget;
      btn.disabled = true; $('#scan-idle', form).hidden = true; $('#scan-run', form).hidden = false;
      for (const m of ['Calibrating sensors…', 'Reading sample spectrum…', 'Amplifying STR loci…']) { $('#scan-msg', form).textContent = m; await GP.sleep(520); }
      sim = { bloodGroup: pick(GROUPS), hb: rnd(90, 175) / 10, wbc: rnd(3800, 13500), glucose: rnd(70, 170), codis: Array.from({ length: 13 }, () => rnd(5, 24)) };
      fillFromSim();
      $('#scan-run', form).hidden = true; btn.disabled = false; btn.textContent = 'Re-run scan';
      GP.clearErrors(form);
      GP.toast('Simulated scan complete.', 'ok', 2200);
    });

    form.addEventListener('submit', async (e) => {
      e.preventDefault();
      GP.clearErrors(form);
      const f = new FormData(form);
      const text = (k) => String(f.get(k) ?? '').trim();
      const payload = {
        name: text('name'), age: text('age') === '' ? '' : Number(text('age')), sex: text('sex'),
        phone: text('phone') || null, bloodGroup: mode === 'simulated' && sim ? sim.bloodGroup : text('bloodGroup'),
        lastDonated: text('lastDonated') || null,
        hb: text('hb') || null, wbc: text('wbc') || null, glucose: text('glucose') || null,
        needsBlood: f.get('needsBlood') === 'on', needsOrgan: text('needsOrgan'), consent: f.get('consent') === 'on',
        dataSource: mode, codis: mode === 'simulated' && sim ? sim.codis : null,
      };
      const early = [];
      if (!payload.name) early.push({ field: 'name', message: 'Enter the full name.' });
      if (payload.age === '' || Number.isNaN(payload.age)) early.push({ field: 'age', message: 'Enter the age.' });
      if (!payload.bloodGroup) early.push({ field: 'bloodGroup', message: 'Select the blood group.' });
      if (mode === 'simulated' && !sim) early.push({ field: 'bloodGroup', message: 'Run the simulated scan first.' });
      if (!payload.consent) early.push({ field: 'consent', message: 'Consent must be confirmed.' });
      if (early.length) { GP.showErrors(form, early); return; }

      const btn = $('#save-btn', form);
      await GP.withBusy(btn, async () => {
        try {
          if (editing) {
            await GP.api('PATCH', `/api/patients/${encodeURIComponent(p.id)}`, payload);
            GP.invalidate(); GP.toast('Changes saved.', 'ok'); location.hash = '#/directory';
            return;
          }
          let res;
          try {
            res = await GP.api('POST', '/api/patients', payload);
          } catch (err) {
            if (err.code !== 'DUPLICATE') throw err;
            const choice = await GP.dialog({
              title: 'Possible duplicate',
              body: html`<p>${err.message}</p><p class="muted">Existing record: <strong>${err.data.existing.name}</strong> (<span class="mono">${err.data.existing.id}</span>).</p>`,
              actions: [{ label: 'Cancel' }, { label: 'View existing', value: 'view' }, { label: 'Register anyway', kind: 'primary', value: 'force' }],
            });
            if (choice === 'view') { GP.openCard(err.data.existing.id); return; }
            if (choice !== 'force') return;
            res = await GP.api('POST', '/api/patients?force=1', payload);
          }
          GP.invalidate(); GP.toast(`${res.patient.name} registered (${res.patient.id}).`, 'ok');
          renderRegister(el);
          GP.openCard(res.patient.id);
        } catch (err) {
          if (err.errors) {
            const rest = GP.showErrors(form, err.errors);
            GP.toast(rest[0] || 'Please fix the highlighted fields.', 'err');
          } else GP.errorToast(err);
        }
      });
    });
    if (!editing) $('#f-name', form).focus({ preventScroll: true });
  }

  GP.views.directory = { title: 'Directory', render: renderDirectory };
  GP.views.register = { title: 'Register', render: renderRegister };
})();
